import { createReadStream } from 'node:fs'
import fs from 'node:fs/promises'
import path from 'node:path'
import { randomUUID } from 'node:crypto'

// C5: temp uploads older than this are leftovers (a crash mid-request, or the old Drive leak).
// A live upload keeps a fresh mtime and Nginx caps a request at 300 s, so an hour is safe.
export const STALE_TEMP_MS = 60 * 60 * 1000

/**
 * STORAGE DRIVER CONTRACT
 * Any driver (local disk now, Google Drive later) implements these four methods and nothing else:
 *
 *   save({ tempPath, ext, folder, fileName }) -> Promise<{ key }>  move/upload a finished temp file, return an opaque key
 *   stat(key)                       -> Promise<{ size }>     throws if the file is gone
 *   createReadStream(key, { start, end }) -> Readable        inclusive byte range, for HTTP Range requests
 *   remove(key)                     -> Promise<void>         idempotent
 *
 * Nothing above this layer knows about paths, folders or Drive file ids; they only hold { driver, key }.
 * A Drive driver would map `key` to a Drive file id, upload from tempPath in save(), and use
 * files.get(alt=media) with a Range header for createReadStream().
 */
// The logger is passed in (storage/index.js passes the app logger) so this driver stays
// importable without the app's environment, as its unit tests rely on.
const silentLog = { info() {}, warn() {} }

export function createLocalDriver(rootDir, { staleTempMs = STALE_TEMP_MS, log = silentLog } = {}) {
  const root = path.resolve(rootDir)

  // Keys are generated by us, but never let one escape the storage root.
  const resolveKey = (key) => {
    if (typeof key !== 'string' || key.split(/[\\/]/).some((segment) => segment === '.' || segment === '..')) {
      throw new Error('Invalid storage key')
    }
    const full = path.resolve(root, key)
    if (full !== root && !full.startsWith(root + path.sep)) throw new Error('Invalid storage key')
    return full
  }

  return {
    name: 'local',
    tempDir: path.join(root, 'tmp'),

    /** Creates the temp folder and clears stale temp files left by earlier runs (C5). */
    async init() {
      const tempDir = path.join(root, 'tmp')
      await fs.mkdir(tempDir, { recursive: true })
      await sweepStaleTempFiles(tempDir, staleTempMs, log)
    },

    async save({ tempPath, ext = '', folder, fileName }) {
      let key = `${folder}/${fileName || `${randomUUID()}${ext}`}`
      if (fileName) {
        const dot = fileName.lastIndexOf('.')
        const stem = dot > 0 ? fileName.slice(0, dot) : fileName
        const suffix = dot > 0 ? fileName.slice(dot) : ''
        for (let n = 2; await fs.stat(resolveKey(key)).then(() => true, () => false); n += 1) {
          key = `${folder}/${stem} (${n})${suffix}`
        }
      }
      const destination = resolveKey(key)
      await fs.mkdir(path.dirname(destination), { recursive: true })
      try {
        await fs.rename(tempPath, destination)
      } catch (error) {
        if (error.code !== 'EXDEV') throw error // temp dir on another disk: copy instead
        await fs.copyFile(tempPath, destination)
        await fs.unlink(tempPath)
      }
      return { key }
    },

    async stat(key) {
      const { size } = await fs.stat(resolveKey(key))
      return { size }
    },

    createReadStream: (key, range) => createReadStream(resolveKey(key), range),

    async remove(key) {
      await fs.unlink(resolveKey(key)).catch((error) => { if (error.code !== 'ENOENT') throw error })
    },
  }
}

/**
 * Deletes regular files directly in `tempDir` whose last modification is older than `maxAgeMs`.
 * Subfolders are left alone. Never fatal: a file that vanishes or cannot be removed is logged
 * and skipped, because a dirty temp folder must not stop the API from starting.
 */
async function sweepStaleTempFiles(tempDir, maxAgeMs, log) {
  const cutoff = Date.now() - maxAgeMs
  let removed = 0
  let entries = []
  try {
    entries = await fs.readdir(tempDir, { withFileTypes: true })
  } catch (error) {
    log.warn({ err: error, tempDir }, 'Could not list the temp folder for clean-up')
    return removed
  }
  for (const entry of entries) {
    if (!entry.isFile()) continue
    const file = path.join(tempDir, entry.name)
    try {
      const { mtimeMs } = await fs.stat(file)
      if (mtimeMs >= cutoff) continue
      await fs.unlink(file)
      removed += 1
    } catch (error) {
      if (error.code !== 'ENOENT') log.warn({ err: error, file }, 'Could not remove a stale temp file')
    }
  }
  if (removed) log.info({ removed, tempDir }, 'Removed stale temp uploads')
  return removed
}
